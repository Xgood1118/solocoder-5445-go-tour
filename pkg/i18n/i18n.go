func T(key string) string {
	langMap, ok := translations[currentLang]
	if !ok {
		langMap = translations[LangZhCN]
	}
	val, ok := langMap[key]
	if !ok {
		enMap := translations[LangEnUS]
		val, ok = enMap[key]
		if !ok {
			return key
		}
	}
	return val
}

func Tf(key string, args ...interface{}) string {
	return fmt.Sprintf(T(key), args...)
}
